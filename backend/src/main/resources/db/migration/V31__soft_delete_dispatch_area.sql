-- =============================================================================
-- V31: 区域软删除（停用）支持
-- =============================================================================
-- 背景：
--   删除区域原来走物理删行（DispatchAreaAdminModule.deleteArea），
--   导致历史订单 dispatch_assignments.area_code 指向不存在的区域（孤儿引用）。
--   改为「分流删除」：
--     * 区域内有历史订单引用 -> 软删除（active=0），保留区域行，
--       历史订单照常显示原区域名，永不产生孤儿；
--     * 区域内无历史订单 -> 物理删除（与创建错想删的场景一致）。
-- 本迁移：
--   给 dispatch_area_bindings 加 active 标记（1=启用，0=停用）。
--   所有读「有效区域」的查询以 active = 1 为过滤条件。
-- =============================================================================

ALTER TABLE dispatch_area_bindings
    ADD COLUMN active TINYINT(1) NOT NULL DEFAULT 1;
