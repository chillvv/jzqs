-- =============================================================================
-- V33: 客户地址门牌号（定位地址与门牌号分开展示，参考京东）
-- =============================================================================
-- 背景：
--   此前 address_line 存完整地址（省市区 + 小区/道路 + 门牌号混在一起），
--   编辑时无法区分「定位地址」和「门牌号」，骑手端展示也把门牌号/备注混在地址里。
--   现拆分为：
--     address_line = 定位地址（省市区 + 小区/道路，顾客地图选点得到）
--     door_number  = 门牌号（几单元几零几），可含用户备注（如"放门口"）
--   骑手端显示时拼接 address_line + door_number。
-- =============================================================================

ALTER TABLE customer_addresses
    ADD COLUMN door_number VARCHAR(100) NULL COMMENT '门牌号（几单元几零几，可含备注如放门口）';
