-- =============================================================================
-- V32: 客户地址经纬度（微信原生地图选点）
-- =============================================================================
-- 背景：
--   骑手导航需要坐标，此前方案是后端调腾讯位置服务做地址文本→坐标的地理编码，
--   该方案涉及第三方商业授权问题，已移除。
--   改为用户小程序端通过 wx.chooseLocation（微信内置地图选点，自带搜索联想+
--   地图拖动微调）在保存地址时直接带回坐标，随地址一起落库；
--   骑手端导航 wx.openLocation 直接用该坐标精确定位。
--   旧地址无坐标时骑手端退化为复制地址自行搜索，不误导航。
-- =============================================================================

ALTER TABLE customer_addresses
    ADD COLUMN latitude DECIMAL(10, 6) NULL COMMENT '纬度（用户微信地图选点）',
    ADD COLUMN longitude DECIMAL(10, 6) NULL COMMENT '经度（用户微信地图选点）';
